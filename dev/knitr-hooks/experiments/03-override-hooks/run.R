d <- dirname(sub("--file=", "", grep("--file=", commandArgs(), value = TRUE)))
source(file.path(d, "..", "lib.R"))
for (q in c("base.qmd", "plot-hook.qmd", "chunk-hook.qmd")) {
  r <- render_docx(d, q)
  cat("\n==", q, "==\n")
  report("render ok", r$status == 0)
  report("caption text present", has(r$xml, "-CAPTION") || has(r$xml, "BASE-CAPTION"))
  report("'Figure 1' crossref prefix generated by Quarto", has(r$xml, "Figure&#160;1") || has(r$xml, "Figure 1") || has(r$xml, "Figure 1"))
  report("crossref link (w:hyperlink w:anchor=fig-a)", has(r$xml, "w:anchor=\"fig-a\""))
  report("no unresolved '@fig-a' / '?@fig-a'", !has(r$xml, "@fig-a"))
  report("CHUNKHOOK-MARKER present", has(r$xml, "CHUNKHOOK-MARKER"))
  if (r$status != 0) cat(tail(r$log, 8), sep = "\n")
}
